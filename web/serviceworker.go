package web

import (
	"encoding/json"
)

// An error here is a bug: the values are paths this process built.
func mustJSON(v any) string {
	b, err := json.Marshal(v)
	if err != nil {
		panic(err)
	}
	return string(b)
}

// Saved pages are mail on disk, so signing in or out, PAGES_DAYS and PAGES_MAX bound them.
const serviceWorker = `// Generated by alborz. Cache version %[1]s.
const VERSION = "%[1]s";
const CACHE = "alborz-shell-" + VERSION;
const PAGES = "alborz-pages";
const SHELL = %[2]s;
const PAGES_MAX = 200;
const PAGES_DAYS = 7;
// How long the network is given before a saved copy answers. A phone on
// a dead connection does not fail a request, it lets it hang.
const NETWORK_WAIT = 5000;
const SAVED_AT = "X-Alborz-Saved";
// What the server sends as a file rather than a page, as patterns of paths.
const DOWNLOADS = %[3]s.map(pattern => new RegExp(pattern));
// Where signing in or out is posted, and the sign-in page; where the shell's files are.
const SIGNINGS = %[4]s;
const SIGN_IN = %[5]s;
const ASSETS = %[6]s;
const ICON = %[7]s;
// The key pushes are signed with, and where a replaced subscription is posted.
const PUSH_KEY = %[8]s;
const RENEW = %[9]s;
// The shell a page was built for; a saved page of another would land under a head that cannot style it.
const SHELL_HEADER = %[10]s;

self.addEventListener("install", event => {
	event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(SHELL)).then(() => self.skipWaiting()));
});

// A new version of the shell means a new cache name; the old ones go,
// so a stale stylesheet cannot outlive a deploy. The pages stay: they
// belong to the reader, not to a version.
self.addEventListener("activate", event => {
	event.waitUntil(caches.keys().then(names =>
		Promise.all(names.filter(name => name !== CACHE && name !== PAGES).map(name => caches.delete(name)))
	).then(() => self.clients.claim()));
});

// What each page's last request met: "offline" a request that failed,
// "slow" one given up on, nothing an answer. The worker says which, since a
// server that takes its time is not a connection that is gone. Pages ask
// when they load and are told when it changes, so the notice that says
// "offline" is never a guess made from the radio's state; and it is per
// page, since another tab's late answer says nothing of what this one shows.
const met = new Map();
const word = client => ({ alborzOffline: met.has(client), alborzSlow: met.get(client) === "slow" });
const tell = async (client, state) => {
	if (state === (met.get(client) || "")) {
		return;
	}
	if (state) {
		met.set(client, state);
	} else {
		met.delete(client);
	}
	const page = await self.clients.get(client);
	if (page) {
		page.postMessage(word(client));
	}
};
self.addEventListener("message", event => {
	if (event.data === "alborz-offline?" && event.source) {
		event.source.postMessage(word(event.source.id));
	}
});

// A fragment and the page it belongs to share a URL and differ in what
// htmx asked for, so the target is part of the key. A boosted click and
// a reload ask for the same document, and share one.
const pageKey = request => {
	const url = new URL(request.url);
	const target = request.headers.get("HX-Target");
	if (target) {
		url.searchParams.set("__hx-target", target);
	}
	return url.href;
};

const savePage = async (key, response) => {
	const headers = new Headers(response.headers);
	headers.set(SAVED_AT, String(Date.now()));
	const cache = await caches.open(PAGES);
	await cache.put(key, new Response(await response.blob(), { status: response.status, headers }));
	const keys = await cache.keys();
	await Promise.all(keys.slice(0, Math.max(0, keys.length - PAGES_MAX)).map(old => cache.delete(old)));
};

const savedPage = async key => {
	const cache = await caches.open(PAGES);
	const saved = await cache.match(key);
	if (saved && Date.now() - Number(saved.headers.get(SAVED_AT)) > PAGES_DAYS * 86400000) {
		await cache.delete(key);
		return undefined;
	}
	if (saved && saved.headers.get(SHELL_HEADER) !== VERSION) {
		return undefined;
	}
	return saved;
};

// The network first, bounded when there is something to fall back on;
// what it answers is kept when it is a page. Any answer at all means
// the server is there, whatever its status.
const page = async (event, ask) => {
	// A navigation's answer is the page it opens, not the one it leaves.
	const client = event.resultingClientId || event.clientId;
	const key = pageKey(event.request);
	const saved = await savedPage(key);
	const patience = new AbortController();
	// A search is as slow as the server's index, and no saved copy of
	// one is worth more than its answer: it is waited for.
	const bounded = saved && !new URL(event.request.url).searchParams.has("query");
	const timer = bounded ? setTimeout(() => patience.abort(), NETWORK_WAIT) : 0;
	try {
		const answer = await ask(patience.signal);
		clearTimeout(timer);
		tell(client, "");
		// Not the sign-in page: it is what a purge leaves behind, and
		// offline it would answer for the page the reader asked for.
		// Nor the pages of a session that locks: what is saved is read
		// offline with no server to ask for the passkey, so such a session
		// keeps nothing, and what it kept before it had a lock goes.
		if ((answer.headers.get("Cache-Control") || "").includes("no-store")) {
			event.waitUntil(caches.delete(PAGES));
		} else if (answer.ok && new URL(event.request.url).pathname !== SIGN_IN &&
			(answer.headers.get("Content-Type") || "").startsWith("text/html")) {
			event.waitUntil(savePage(key, answer.clone()));
		}
		return answer;
	} catch (failure) {
		clearTimeout(timer);
		tell(client, patience.signal.aborted ? "slow" : "offline");
		if (saved) {
			return saved;
		}
		throw failure;
	}
};

// A push says only what the server rendered for this browser (ADR 74); a click brings the app to its page.
self.addEventListener("push", event => {
	const note = event.data.json();
	const shown = [self.registration.showNotification(note.title, { body: note.body, tag: note.tag, icon: ICON, data: { url: note.url } })];
	if (note.badge && self.navigator.setAppBadge) {
		shown.push(self.navigator.setAppBadge().catch(() => {}));
	}
	event.waitUntil(Promise.all(shown));
});

// A push service may replace a subscription; the server swaps it in for every account of this browser
// that had the old one. A browser that does not name the old one is turned on again by hand.
self.addEventListener("pushsubscriptionchange", event => {
	const old = event.oldSubscription;
	if (!old) {
		return;
	}
	const renewed = event.newSubscription ? Promise.resolve(event.newSubscription) :
		self.registration.pushManager.subscribe({ userVisibleOnly: true, applicationServerKey: PUSH_KEY });
	event.waitUntil(renewed.then(sub => {
		const json = sub.toJSON();
		const form = new URLSearchParams({ old: old.endpoint, endpoint: json.endpoint, p256dh: json.keys.p256dh, auth: json.keys.auth });
		return fetch(RENEW, { method: "POST", body: form, credentials: "same-origin", redirect: "manual" });
	}));
});

self.addEventListener("notificationclick", event => {
	event.notification.close();
	const url = new URL(event.notification.data.url, self.location.origin).href;
	event.waitUntil(self.clients.matchAll({ type: "window" }).then(windows => {
		const open = windows.find(w => new URL(w.url).origin === self.location.origin);
		if (!open) {
			return self.clients.openWindow(url);
		}
		return open.focus().then(w => w.navigate(url));
	}));
});

self.addEventListener("fetch", event => {
	const request = event.request;
	const url = new URL(request.url);
	if (url.origin !== self.location.origin) {
		return;
	}
	// Signing in or out ends what was saved: the pages were one
	// reader's, and the next one at this browser may be another. The
	// page of browsers signed in is among them because it signs this
	// one out too, and a POST's answer is a redirect the worker cannot
	// read to tell which browser it was.
	if (request.method === "POST" && SIGNINGS.includes(url.pathname)) {
		event.waitUntil(caches.delete(PAGES));
		return;
	}
	if (request.method !== "GET") {
		return;
	}
	// The shell is stamped with a digest, so a hit is the right file by
	// construction and a miss fetches and keeps the new one.
	if (url.pathname.startsWith(ASSETS)) {
		event.respondWith(caches.match(request).then(hit => hit || fetch(request).then(answer => {
			if (answer.ok) {
				const copy = answer.clone();
				caches.open(CACHE).then(cache => cache.put(request, copy));
			}
			return answer;
		})));
		return;
	}
	// Never from the browser's own store: pages carry no cache headers,
	// so a heuristically fresh copy would answer a reload with
	// yesterday's page - which in an installed window, where there is
	// no address bar to force the issue, looks like an application that
	// cannot be updated.
	// A download is a navigation the browser ends by saving a file, and
	// a worker in the middle of one leaves an installed window loading
	// for ever: nothing is shown, nothing is saved. These answer as
	// themselves, straight from the network.
	if (DOWNLOADS.some(pattern => pattern.test(url.pathname))) {
		return;
	}
	if (request.mode === "navigate") {
		// redirect manual, not follow: a response a worker followed
		// cannot be handed back for a navigation, and most of alborz's
		// pages answer a redirect - a post that lands, a URL made
		// canonical. Manual hands the browser the redirect itself and
		// it navigates again, through here, fresh.
		event.respondWith(
			// A page never saved fails as any page does offline: the
			// browser says so in its own words.
			page(event, signal => fetch(request.url, { cache: "reload", credentials: "same-origin", redirect: "manual", signal }))
		);
		return;
	}
	// What htmx asks for: a boosted page or a fragment of one. The
	// event stream and downloads are neither, and pass untouched. So
	// does a search: a page that gives one up aborts its fetch, and
	// only the browser's own fetch carries that to the server, which
	// then stops searching; a worker's fetch never learns of it.
	if (request.headers.get("HX-Request") === "true" && !url.searchParams.has("query")) {
		event.respondWith(page(event, signal => fetch(request, { signal })));
	}
});
`
