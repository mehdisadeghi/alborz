// languages are the supported UI languages, in fallback order.
var languages = []string{"en", "fa", "de", "es"}

// MatchLanguage picks the first supported language named in an
// Accept-Language header, falling back to English.
func MatchLanguage(header string) string {
	for part := range strings.SplitSeq(header, ",") {
		tag, _, _ := strings.Cut(part, ";")
		tag, _, _ = strings.Cut(strings.ToLower(strings.TrimSpace(tag)), "-")
		if IsLanguage(tag) {
			return tag
		}
	}
	return "en"
}

// IsLanguage reports whether the code names a supported UI language.
func IsLanguage(code string) bool {
	return slices.Contains(languages, code)
}

func translate(lang, key string) string {
	if m, ok := catalogs[lang]; ok {
		if s, ok := m[key]; ok {
			return s
		}
	}
	if s, ok := catalogs["en"][key]; ok {
		return s
	}
	return key
}

